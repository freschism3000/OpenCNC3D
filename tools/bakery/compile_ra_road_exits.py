#!/usr/bin/env python3
"""Compile RA's native logical road exits; never classify live Enhanced RGB.

Snow and Temperate share D01..D45 template topology. The native Snow palette
makes that common road path explicit. Retain only the main connected road,
then save its24 edge bits for each icon. This extends the existing source-led
road-exit authoring audit, without repainting either theater.
"""
from pathlib import Path
import hashlib,importlib.util,json
import numpy as np
from scipy import ndimage as nd
ROOT=Path(__file__).resolve().parents[2]
def build():
 p=ROOT/'tools/ra3d/bake_ra_terrain3d.py';spec=importlib.util.spec_from_file_location('ra',p);ra=importlib.util.module_from_spec(spec);spec.loader.exec_module(ra)
 palette=ra.palette('SNOW.PAL');slots=ra.bank_slots('RASNOW');meta=json.loads((ROOT/'art/remaster/textures/RASNOW/set_144.json').read_text())['templates'];temperate=json.loads((ROOT/'art/remaster/textures/RATEMP/set_144.json').read_text())['templates'];table=[[]for _ in range(46)];rows=[]
 for name,row in meta.items():
  if not(name.startswith('D')and name[1:].isdigit()):continue
  number=int(name[1:]);w,h=row['cells'];assert row['cells']==temperate[name]['cells'] and row['have']==temperate[name]['have'];assert w*h<=16
  native=np.zeros((h*24,w*24,3),np.uint8);occupied=np.zeros((h*24,w*24),bool);digest=hashlib.sha256()
  for tid,icon,data in slots:
   if tid!=row['tid']:continue
   y,x=divmod(icon,w);native[y*24:(y+1)*24,x*24:(x+1)*24]=palette[np.frombuffer(data,np.uint8)].reshape(24,24,3);occupied[y*24:(y+1)*24,x*24:(x+1)*24]=True;digest.update(bytes([icon]));digest.update(data)
  weight=nd.gaussian_filter(occupied.astype(float),.65)
  luminance=nd.gaussian_filter(native.mean(2).astype(float)*occupied,.65)/np.maximum(weight,1e-6)
  road=(luminance<190)&occupied
  labels,count=nd.label(road,np.ones((3,3)));sizes=np.bincount(labels.ravel());sizes[0]=0;road=labels==sizes.argmax()
  masks=[]
  for icon in range(w*h):
   y,x=divmod(icon,w);q=road[y*24:(y+1)*24,x*24:(x+1)*24];edges=[q[:,0],q[:,-1],q[0],q[-1]];masks.append([sum(int(v)<<i for i,v in enumerate(edge))for edge in edges])
  table[number]=masks;rows.append(dict(name=name,cells=[w,h],have=row['have'],native_sha256=digest.hexdigest(),edge_masks=masks))
 header='''#ifndef CNC3D_RA_ROAD_EXITS_H
#define CNC3D_RA_ROAD_EXITS_H
// Generated by tools/bakery/compile_ra_road_exits.py from native road topology.
// Sides L,R,T,B; bits run north-to-south or west-to-east in world order.
static const unsigned g_raRoadExit[46][16][4]={\n'''
 header+=',\n'.join('  {'+','.join('{'+','.join('0x%06xu'%v for v in edge)+'}'for edge in icons)+'}'for icons in table)+'\n};\n'
 header+='''static bool ra_road_exits_connect(int a,int ai,int side,int b,int bi)
{
    if(a<1||a>45||b<1||b>45||ai<0||ai>=16||bi<0||bi>=16||side<0||side>3)return false;
    unsigned overlap=g_raRoadExit[a][ai][side]&g_raRoadExit[b][bi][side^1];
    int count=0;for(;overlap;overlap&=overlap-1)++count;
    return count>=3;
}
#endif
'''
 (ROOT/'game/ra3d_road_exits.h').write_text(header)
 out=ROOT/'art/remaster/textures/ra_road_continuity_v01/native_exits_v02.json';out.write_text(json.dumps(dict(schema=1,source='Original RA Snow indexed tiles and SNOW.PAL; common D01..D45 logical exits, matching Temperate layouts',coordinate_contract='24 native bits along L/R/T/B; matching world-edge direction, minimum3 overlapping road pixels',templates=rows),indent=2)+'\n')
 print('compiled',len(rows),'native road templates');print('D39.0 bottom/D35.2 top',hex(table[39][0][3]),hex(table[35][2][2]));print('D35.2 right/D39.3 left',hex(table[35][2][1]),hex(table[39][3][0]))
if __name__=='__main__':build()
